create policy ocorrencias_entregas_autenticados on public.ocorrencias_entregas
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists ocorrencias_entregas_itens_autenticados on public.ocorrencias_entregas_itens;
create policy ocorrencias_entregas_itens_autenticados on public.ocorrencias_entregas_itens
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

