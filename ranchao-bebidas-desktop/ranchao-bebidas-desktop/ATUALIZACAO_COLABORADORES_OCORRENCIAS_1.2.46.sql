create table if not exists public.ocorrencias_entregas (
  id bigint generated by default as identity primary key,
  loja text not null,
  data_entrega date not null,
  fornecedor text not null,
  pedido text,
  nota_fiscal text,
  tipo text not null,
  providencia text,
  status text not null default 'pendente',
  prazo_fornecedor date,
  responsavel text,
  descricao text not null,
  data_resolucao date,
  solucao text,
  valor_recuperado numeric(14,2) not null default 0,
  arquivo_nome text,
  arquivo_tipo text,
  caminho_storage text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ocorrencias_entregas_itens (
  id bigint generated by default as identity primary key,
  ocorrencia_id bigint not null references public.ocorrencias_entregas(id) on delete cascade,
  produto text not null,
  quantidade_pedida numeric(14,3) not null default 0,
  quantidade_recebida numeric(14,3) not null default 0,
  quantidade_afetada numeric(14,3) not null default 0,
  custo_unitario numeric(14,2) not null default 0,
  ordem integer not null default 1,
  created_at timestamptz not null default now()
);

create index if not exists ocorrencias_entregas_loja_data_idx on public.ocorrencias_entregas(loja,data_entrega desc);
create index if not exists ocorrencias_entregas_status_idx on public.ocorrencias_entregas(loja,status);
create index if not exists ocorrencias_entregas_itens_ocorrencia_idx on public.ocorrencias_entregas_itens(ocorrencia_id);

alter table public.ocorrencias_entregas enable row level security;
alter table public.ocorrencias_entregas_itens enable row level security;

