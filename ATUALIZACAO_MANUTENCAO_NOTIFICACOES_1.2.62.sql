create table if not exists public.manutencoes_arquivos (
  id bigint generated by default as identity primary key,
  manutencao_id text not null,
  loja text not null,
  caminho_storage text not null,
  arquivo_nome text,
  arquivo_tipo text,
  tamanho_bytes bigint,
  criado_em timestamptz not null default now()
);

create index if not exists manutencoes_arquivos_manutencao_idx
  on public.manutencoes_arquivos (manutencao_id);

insert into public.manutencoes_arquivos
  (manutencao_id, loja, caminho_storage, arquivo_nome, arquivo_tipo)
select m.id::text, m.loja, m.caminho_storage, m.arquivo_nome, m.arquivo_tipo
from public.manutencoes m
where m.caminho_storage is not null
  and not exists (
    select 1 from public.manutencoes_arquivos a
    where a.manutencao_id = m.id::text and a.caminho_storage = m.caminho_storage
  );

