create table if not exists public.metas_vendas_config (
  id bigint generated by default as identity primary key,
  loja text not null check (loja in ('loja1','loja2')),
  mes date not null,
  meta_mensal numeric(14,2) not null default 0 check (meta_mensal >= 0),
  peso_seg_qua numeric(8,3) not null default 0.7 check (peso_seg_qua > 0),
  peso_quinta numeric(8,3) not null default 1 check (peso_quinta > 0),
  peso_sexta numeric(8,3) not null default 1.4 check (peso_sexta > 0),
  peso_sabado numeric(8,3) not null default 1.8 check (peso_sabado > 0),
  peso_domingo numeric(8,3) not null default 1.1 check (peso_domingo > 0),
  peso_feriado numeric(8,3) not null default 1.5 check (peso_feriado > 0),
  atualizado_em timestamptz not null default now(),
  unique (loja, mes)
);

create table if not exists public.metas_vendas_dias (
  id bigint generated by default as identity primary key,
  loja text not null check (loja in ('loja1','loja2')),
  data date not null,
  venda_manual numeric(14,2) check (venda_manual is null or venda_manual >= 0),
  nome_especial text,
  peso_manual numeric(8,3) check (peso_manual is null or peso_manual > 0),
  atualizado_em timestamptz not null default now(),
  unique (loja, data)
);

create index if not exists metas_vendas_config_loja_mes_idx on public.metas_vendas_config (loja, mes);
create index if not exists metas_vendas_dias_loja_data_idx on public.metas_vendas_dias (loja, data);

alter table public.metas_vendas_config enable row level security;
alter table public.metas_vendas_dias enable row level security;

drop policy if exists "metas_config_usuario_autenticado" on public.metas_vendas_config;
create policy "metas_config_usuario_autenticado" on public.metas_vendas_config
  for all to authenticated using (true) with check (true);

drop policy if exists "metas_dias_usuario_autenticado" on public.metas_vendas_dias;
create policy "metas_dias_usuario_autenticado" on public.metas_vendas_dias
  for all to authenticated using (true) with check (true);

grant select, insert, update, delete on public.metas_vendas_config to authenticated;
grant select, insert, update, delete on public.metas_vendas_dias to authenticated;
grant usage, select on all sequences in schema public to authenticated;
